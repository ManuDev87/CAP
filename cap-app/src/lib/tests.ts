function regionTestsFlat(region: CommunityRegion): TestMeta[] {
  if (region.subregions?.length) {
    return region.subregions.flatMap((s) => s.tests);
  }
  return region.tests;
}

/** Flat list of all tests (compat for loaders / stats / getTestMeta). */
export const availableTests: TestMeta[] = [
  ...communityRegions.flatMap(regionTestsFlat),
  ...viajerosCommunityRegions.flatMap(regionTestsFlat),
];

export function regionTestCount(region: CommunityRegion): number {
  return regionTestsFlat(region).length;
}

function pruneEmptyRegions(regions: CommunityRegion[]): CommunityRegion[] {
  return regions
    .map((region) => {
      if (!region.subregions?.length) return region;
      return {
        ...region,
        subregions: region.subregions.filter((sub) => sub.tests.length > 0),
      };
    })
    .filter((region) => regionTestCount(region) > 0);
}

export function regionsForTrack(track: "mercancias" | "viajeros"): CommunityRegion[] {
  const src = track === "viajeros" ? viajerosCommunityRegions : communityRegions;
  return pruneEmptyRegions(src);
}

